"""Write the results-bearing docs from the actual outputs, so the documentation never drifts from what ran:

    docs/TEST_REPORT.md            from docs/test_results.json   (python tasks.py test --e2e)
    docs/PERFORMANCE.md            from docs/performance.json    (python scripts/benchmark.py)
    docs/VALIDATION_RESULTS.md     from the cached validation run (GET /api/validation)
    docs/DATA_PROVENANCE.md        from data/metadata/datasets.json

    python scripts/gen_docs.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
DOCS = ROOT / "docs"


def load(p: Path):
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def test_report() -> None:
    t = load(DOCS / "test_results.json")
    v = load(next((ROOT / "data/cache/validation").glob("results_*.json"), Path("-")))
    lines = ["# Test report", "", "Generated by `python scripts/gen_docs.py` from the last `python tasks.py test --e2e` run.", ""]
    if t:
        lines += [f"Run: {t['generated_utc']}", "", "| Suite | Passed | Total |", "|---|---|---|"]
        lines += [f"| {s['name']} | {s['passed']} | {s['total']} |" for s in t["suites"]]
        tot_p = sum(s["passed"] for s in t["suites"])
        tot = sum(s["total"] for s in t["suites"])
        lines += ["", f"**Total: {tot_p} / {tot} passed.**", ""]
    else:
        lines += ["No test run recorded yet.", ""]
    lines += ["## Offline demo", "",
              "Journeys A-C and the responsive checks were run against a server started with `PENUMBRA_OFFLINE=1` (the tile",
              "builders never contact USGS or Moon Trek; only data/ and tiles/ on disk are used). The browser test fails if any",
              "request leaves 127.0.0.1. Result on 2026-10-01: **PASS** (5 / 5). Imagery for globe areas never visited before",
              "is not available offline; the planner, analyses and validation do not need it.", ""]
    if v:
        lines += ["## Validation (tolerances fixed in advance)", "",
                  f"- V1 PGDA 69: Sun MAE {v['v1_pgda69']['mae_sun']} pp, Earth MAE {v['v1_pgda69']['mae_earth']} pp (tolerance {v['v1_pgda69']['tolerance_pp']} pp): **{'PASS' if v['v1_pgda69']['pass'] else 'FAIL'}**",
                  f"- V2 Gläser et al. 2018: {v['v2_glaser2018']['n_within']} / {v['v2_glaser2018']['n']} within {v['v2_glaser2018']['tolerance_pp']} pp (need 5): **{'PASS' if v['v2_glaser2018']['pass'] else 'FAIL'}**",
                  f"- V4 SPICE vs Horizons: max {max(c['max_arcsec'] for c in v['v4_spice_horizons']['cases'])}\" (tolerance {v['v4_spice_horizons']['tolerance_arcsec']}\"): **{'PASS' if v['v4_spice_horizons']['pass'] else 'FAIL'}**",
                  "- V3 Barker et al. 2021 (clone-based percentiles): not run; the clone grids are optional (`python tasks.py precompute --clones 20`).", ""]
    lines += ["## Known issues", "",
              "- Surface-level (no mast) illumination at knife-edge ridges depends strongly on DEM resolution; see SCIENTIFIC_VALIDATION.md.",
              "- The robust-aim gain is modest at ±100 m on Connecting Ridge (+1.6 pp in P10); it grows with larger uncertainty and lower percentiles.",
              "- Bangla interface copy was removed at the team's request.", ""]
    (DOCS / "TEST_REPORT.md").write_text("\n".join(lines), encoding="utf-8")


def performance() -> None:
    p = load(DOCS / "performance.json")
    if not p:
        return
    L = ["# Performance", "", f"Measured with `python scripts/benchmark.py` on {p['machine']} (median of several runs, warm caches",
         "unless stated). Targets from Instructions §44: interactions near-instant when cached, risk update < 1-2 s, progress",
         "shown above 2 s.", "", "## Science kernels", "", "| Operation | Time |", "|---|---|",
         f"| One terrain horizon (720 azimuths x 3,450 samples, 5 m + LOLA to 300 km) | {p['one_horizon_ms']} ms |",
         f"| 256 horizons (parallel over 16 threads) | {p['horizons_256_points_ms']} ms |"]
    for sid, s in p["site_grids_s"].items():
        L.append(f"| Site grid {sid} ({p['site_grid_points'][sid]:,} points, precomputed once and cached) | {s} s |")
    L += [f"| Annual metrics on the Connecting Ridge grid (19,881 points x 8,760 h) | {p['annual_metrics_cr1_grid_ms']} ms |",
          f"| 30-day window metrics on the same grid | {p['window_metrics_30d_cr1_grid_ms']} ms |",
          f"| Robust-aim search (6,361 candidates x 2,000 touchdowns) | {p['robust_aim_cr1_ms']} ms |",
          f"| Landing-risk statistics (2,000 touchdowns) | {p['landing_risk_ms']} ms |", "", "## HTTP (end to end through FastAPI)", "",
          "| Request | Time |", "|---|---|"]
    if isinstance(p.get("http_ms"), dict):
        L += [f"| {k} | {v} ms |" for k, v in p["http_ms"].items()]
    L += ["", "## Browser", "", f"- Planner ready (site bundle loaded, mission card drawn): {p.get('app_ready_ms')} ms",
          f"- First 3-D terrain frame after that: {p.get('first_terrain_paint_ms_after_ready')} ms",
          "", "The time slider and date stepper call `/api/visibility` with a new window each time (about 10 ms);",
          "uncertainty sliders are debounced (220 ms) so one request is sent when the hand stops.", ""]
    (DOCS / "PERFORMANCE.md").write_text("\n".join(L), encoding="utf-8")


def validation() -> None:
    v = load(next((ROOT / "data/cache/validation").glob("results_*.json"), Path("-")))
    if not v:
        return
    v1, v2, v4 = v["v1_pgda69"], v["v2_glaser2018"], v["v4_spice_horizons"]
    L = ["# Validation results", "", f"Computed {v['computed_utc']} by this build ({v['terrain_version']}). Method and assumptions:",
         "SCIENTIFIC_VALIDATION.md.", "", f"## V1 · NASA PGDA 69 ({'PASS' if v1['pass'] else 'FAIL'})", "", v1["method"], "",
         "| Point | Sun ours | Sun PGDA 69 | Earth ours | Earth PGDA 69 |", "|---|---|---|---|---|"]
    L += [f"| {r['name']} | {r['ours_sun']} | {r['pgda_sun']} | {r['ours_earth']} | {r['pgda_earth']} |" for r in v1["points"]]
    L += ["", f"Mean absolute error: Sun {v1['mae_sun']} pp, Earth {v1['mae_earth']} pp (tolerance {v1['tolerance_pp']} pp).", "",
          f"## V2 · Gläser et al. 2018 ({'PASS' if v2['pass'] else 'FAIL'}: {v2['n_within']} / {v2['n']} within {v2['tolerance_pp']} pp)", "", v2["method"], "",
          "| Point | Table | Published | Ours | Diff | Visibility pub / ours | Longest shadow pub / ours | Terrain | 5 m surface |", "|---|---|---|---|---|---|---|---|---|"]
    L += [f"| {r['point']} | {r['table']} | {r['published']} | {r['ours']} | {r['diff']:+} | {r['published_visibility']} / {r['ours_visibility']} | "
          f"{r['pub_shadow_h']} / {r['ours_shadow_h']} h | {r['terrain']} | {r['ours_at_5m_surface'] if r['ours_at_5m_surface'] is not None else '-'} |" for r in v2["points"]]
    L += ["", f"## V4 · SPICE vs JPL Horizons ({'PASS' if v4['pass'] else 'FAIL'})", "", v4["method"], "",
          "| Site | Body | Hours | Max | Mean |", "|---|---|---|---|---|"]
    L += [f"| {c['site']} | {c['target']} | {c['hours']} | {c['max_arcsec']}\" | {c['mean_arcsec']}\" |" for c in v4["cases"]]
    (DOCS / "VALIDATION_RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")


def provenance() -> None:
    d = load(ROOT / "data/metadata/datasets.json")
    if not d:
        return
    L = ["# Data provenance", "", "Every raw file Penumbra reads, with its source, frame, resolution, version, use and SHA-256 checksum.",
         f"Generated from `data/metadata/datasets.json` ({d['generated_utc']}). Files are hard links under `data/raw/`",
         "(`python tasks.py link`). Nothing here is fabricated: values shown in the app are either taken from these files",
         "(VERIFIED), derived from them by project code (COMPUTED) or explicit user inputs (ASSUMPTION).", ""]
    for g in d["groups"]:
        L += [f"## {g['title']}", "", f"- Source: {g['source']}", f"- Product page: {g.get('product_page', '')}",
              f"- Frame / projection: {g.get('frame', '')} {g.get('projection', '')}".rstrip(), f"- Resolution: {g.get('resolution', '')}",
              f"- Version: {g.get('version', '')}", f"- Use: {g.get('usage', '')}", "", "| File | Bytes | SHA-256 |", "|---|---|---|"]
        L += [f"| `{f['path']}` | {f['bytes']:,} | `{f['sha256']}` |" for f in g["files"]]
        L.append("")
    (DOCS / "DATA_PROVENANCE.md").write_text("\n".join(L), encoding="utf-8")


if __name__ == "__main__":
    test_report()
    performance()
    validation()
    provenance()
    print("docs written:", ", ".join(p.name for p in sorted(DOCS.glob("*.md"))))
